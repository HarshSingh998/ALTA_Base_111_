def add(a, b):
    return a + b


# Integer addition
int1 = int(input("Enter first integer: "))
int2 = int(input("Enter second integer: "))

# Float addition
float1 = float(input("Enter first float number: "))
float2 = float(input("Enter second float number: "))

print("Integer addition:", add(int1, int2))
print("Float addition:", add(float1, float2))










